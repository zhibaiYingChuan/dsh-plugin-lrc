/**
 * 记忆 schema：**「一条记忆是什么」的唯一真理源**。
 *
 * ## 为什么必须有这个文件
 *
 * 此前插件有 6 条并行写入路径（标签 / 正文正则 / 用户纠正 / 资源位置 /
 * 服务端 distill 透传 / LLM 兜底），每条路径各自带长度门槛、各自带
 * 词表、各自决定「写还是不写」。任何一次修复只覆盖其中一条，其余五条
 * 继续漏或继续脏 —— 这是「改了十一轮还在反复」的机械原因。
 *
 * 根本缺陷不在判据精度，而在**从未定义过「一条记忆」这个对象**：
 * 所有正则都在做「这个句子像不像约束」的二分类，而二分类的假设空间
 * 是无限的（措辞无穷），永远补不完。
 *
 * ## 现在的模型：记忆 = 三元组 + 元数据
 *
 * ```
 * Fact = (kind, subject, predicate, value) + (scope, origin, confidence, source, status)
 * ```
 *
 * 三元组**缺一即不是记忆**。这条规则替代了此前所有的长度门槛 ——
 * `这必须用上` 被拒不是因为「只有 6 个字」，而是因为它拆不出 value；
 * `那我得确认两件事` 被拒不是因为它带「得」，而是因为它不自足。
 *
 * ## 与成熟方案的对齐
 *
 * | 方案 | 契约形态 |
 * |---|---|
 * | mem0 v3 | 单遍 ADD-only，JSON facts 数组 |
 * | NeuSymMS | `{subject, relation, value, confidence, scope}` |
 * | xmemory（2026-08） | schema 定义「必须记住 / 可以忽略 / 绝不推断」 |
 *
 * 三家一致：**schema-first，不是 keyword-first**。本文件就是那个 schema。
 *
 * 本模块是纯函数，不依赖宿主，可直接单测（见 `scripts/e2e-schema.ts`）。
 */

/** 记忆类别。 */
export type FactKind = 'constraint' | 'decision' | 'conclusion' | 'goal' | 'location' | 'artifact' | 'statement' | 'fact';

/** 生效范围。`session` 表示临时参数，不该跨会话召回。 */
export type FactScope = 'project' | 'session';

/** 生命周期状态。`superseded` / `retracted` 的记录仍保留，但不再注入。 */
export type FactStatus = 'active' | 'superseded' | 'retracted';

/**
 * 一条记忆。
 *
 * ## 三元组从「准入条件」降级为「富集项」（★2026-11-14 六钥匙重定向）
 *
 * 旧契约是「三元组缺一即不是记忆」。实测 7258 字符的真实分析报告：
 *
 * | 判据 | 通过数 |
 * |---|---|
 * | 候选句（8–200 字符，已去表格/标题/代码） | 82 |
 * | 通过全部**结构**判据（自足/非过程叙述/非疑问/非机器输出） | **82 / 82** |
 * | 通过 95 词**谓词白名单** | **3 / 82** |
 *
 * 结构判据零误杀（它们全部可计算），真正的瓶颈是那个白名单挡掉了 96%
 * 的句子 —— 而其中大量是「分层极其干净，改造成本低」这种真判断句。
 *
 * 根因是**分类错位**：「这句是不是可复用陈述」是**语义**问题，需要理解；
 * 用 95 个词的封闭词表去近似开放语言，必然漏。三元组只是陈述的**一种
 * 形态**，不是陈述的必要条件。
 *
 * 因此现在的契约分两层：
 * 1. `statement` 是**唯一必填**：只要是自足的陈述句就是一条记忆
 * 2. 三元组**可为空**：拆得出就填（用于冲突判定 / 去重 / 排序），
 *    拆不出不影响入库 —— 95 个谓词从「否决权」变成「富集能力」
 *
 * 语义判定（这句到底值不值得记）交给 LLM 兜底整条消息一次调用，
 * 而不是靠词表逐句二分类。
 */
export interface MemoryFact {
  kind: FactKind;
  /** 主体：这条记忆在说谁 / 什么（`缓存`、`端口`、`score.wav`）。可为空（全局规则）。 */
  subject: string;
  /** 关系：`必须`、`改用`、`位于`、`根因是`。可为空（未富集）。 */
  predicate: string;
  /** 取值：`pnpm`、`--stdin`、`桌面`、`200ms`。可为空（未富集）。 */
  value: string;
  /** 自然语言陈述（自足、脱离上下文可懂）。**唯一必填字段**。 */
  statement: string;
  scope: FactScope;
  origin: 'user' | 'assistant';
  /** 置信度 0..1。规则层给高值，LLM 层给中值。 */
  confidence: number;
  source: { sessionId: string; turn?: number };
  status: FactStatus;
  /**
   * 是否已富集成三元组。
   *
   * `false` 表示「陈述成立，但没拆出 subject/predicate/value」——
   * 这类 Fact 仍可入库、可注入、可召回，只是不参与冲突判定。
   */
  enriched?: boolean;
  /**
   * 所在消息的主题（**上下文附加**，★2026-11-17）。
   *
   * ## 为什么需要它（真实数据决定）
   *
   * 实测 session-95eaf7e3（1578 条助手消息 / 266 条 Fact）：
   * - **67.3% 的 Fact ≤ 20 字**，**69.5% 有上下文依赖特征**
   * - 例：`[约束] 必须是 12 的倍数` —— 谁的 12 的倍数？脱离原文无从判断
   *
   * 同时实测否定了「按段落合并」这条路：含 ≥2 段落的消息仅 **5.6%**，
   * markdown 标题仅 **0.7%** —— DSH 的正文几乎没有段落结构可依。
   *
   * 但 **99.2% 的消息有可用首句**。因此正确做法不是改切分单元，而是
   * **给每条 Fact 附上它所在消息的主题**（业界称 contextual retrieval）。
   *
   * ## 为什么是可选字段
   *
   * 缺省时行为与引入本字段前**逐字一致**（statement / 去重 / 快照全不变）。
   * `topic` 只用于：
   * 1. 写入时落成 `topic:xxx` 标签（供按主题过滤）
   * 2. 折叠摘要的标题（替代「本批 N 条：」）
   */
  topic?: string;
}

