const PLANNING_AFTER_DECLARATION =
  /(?:目标|结论)\s*(?:是|为|：|:)\s*(?:先|再|准备|打算|将要|待|接下来|下一步|后续)|(?:下一步|接下来|后续|然后|下面|接着)\s*目标/;

/**
 * 疑问句：提问不是断言，**不可能**是一条记忆。
 *
 * ```
 * 数据库为什么选 PostgreSQL 而不是 MySQL    ← 提问
 * 数据库选 PostgreSQL                       ← 决策
 * 说明为什么改用 --stdin                    ← 陈述（在解释原因）
 * ```
 * 三条文本形态几乎一样。判据必须同时看**疑问词**和它前面是不是
 * 「解释类动词」—— 只有后者才不是提问。解释类动词是封闭集合（可枚举），
 * 不会像早期正则那样无限膨胀。
 */
const QUESTION_TAIL = /[？?]\s*$|(?:吗|呢)\s*$/;
const QUESTION_WORD = /为什么|为何|怎么|如何|是否|有没有|是不是|能不能|可不可以|哪里|哪儿|哪个|哪些|多少|请问/;

/**
 * **正反问句**（A-not-A）—— 疑问式的**结构**判据（★2026-11-15）。
 *
 * ## 为什么必须有这条
 *
 * `QUESTION_WORD` 是封闭枚举（12 个词），实测仍然整类漏掉：
 * ```
 * 要不要横向再收窄一点     ← 漏 ⇒ 被判为 constraint，rank 0
 * 能否改成 SVG            ← 漏
 * 该不该改                ← 漏
 * ```
 * 后果不是「多收一条」而是**挤占**：`keepPriority` 给 constraint 排 rank 0，
 * 快照只有 3 个槽位 —— 一句疑问残留会挤掉 `必须完整经历五屏引导`。
 *
 * ## 为什么**不锚定位置**（★2026-11-15 第二轮独立审查 P0-2）
 *
 * 首版锚定「句首 / 分句首」，实测漏掉这类最常见的真实位置：
 * ```
 * 遮罩要不要改成变量      ← 句中最常见形态（这个 X 要不要 Y）
 * 端口要不要换成 3099
 * ```
 * 漏掉的后果是**语义反转**：被切成 `(遮罩要|不要|改成变量)` 存成
 * **constraint**（禁令），提问被记成规则，rank0 独占快照槽位。
 *
 * 而 `要/不` 两字本身已足够区分：
 * ```
 * 不要碰 3099        ← `不` 在 `要` 前，不匹配
 * 要不是先跑测试      ← `要是` 连读，不匹配
 * 可不要再碰          ← `可不` 连读，不匹配
 * 有无线网络          ← `有无` 不在列表
 * 动不动 / 时不时 / 不得不  ← 叠词，不在列表
 * ```
 * 14 个正/反样本实测全对（见 `e2e-schema` 第 21 节）。
 *
 * ## 形态清单（封闭语法类）
 *
 * ```
 * 要不要 / 是不是 / 能不能 / 能否 / 会不会 / 该不该
 * 可不可以 / 可否 / 应不应该 / 有无
 * ```
 *
 * `有无` 必须带词边界（见 `A_NOT_A_HAS`），否则 `有无线网络` 会被误判。
 */
const A_NOT_A_QUESTION = /(?:要不要|是不是|能不能|能否|会不会|该不该|可不可以|应不应该|可否)/;

/**
 * `有无` 的正反问形态 —— **必须带词边界**（★2026-11-15 第二轮审查 P0-3）。
 *
 * ```
 * 有无更优解            ← 正反问（`有无` 后接「更」）
 * 有无线网络必须先关掉    ← `有` + `无线`（网络），不是疑问
 * 有无效的字段要过滤      ← `有` + `无效`
 * 有无法访问的路径        ← `有` + `无法`
 * ```
 * 汉语里 `有` 后接否定词修饰的名词极常见，而 `有无` 作疑问只出现在
 * 「有无 + 名词」。区分不了词性时，**只认带标点的明确形态**：
 * 句尾、或后面紧跟问号。
 */
const A_NOT_A_HAS = /有无(?:$|[？?，,。；;])|有无(?:更|其|任|何|哪)/;

/** 解释类动词：出现在疑问词之前时，该句是在解释而不是在提问。 */
const EXPLANATION_VERB = /(?:说明|解释|讲清楚?|搞清楚?|查清楚?|弄清楚?|写明|记录|分析|确认|判断|理解)$/;
/**
 * 反问 / 纠正句式：用户在用反问强调「我已经说过了」。
 *
 * ```
 * 不是告诉你音频在的位置了吗？
 * 我说过多少次了，别用 IDM
 * 早就跟你说过不要点下载
 * 跟你说多少遍了别用 IDM      ← ★2026-11-15 第二轮审查 P1-2
 * ```
 * 这类句子在语义上等价于一条禁令，是整场会话里最强的约束信号。
 *
 * ## 为什么必须补「跟你说多少遍」
 *
 * 首版只认「我说过 N 次」，漏掉主语为「跟你」的口语形态。而
 * `QUESTION_WORD` 里恰好有「多少」，于是它被**反向硬拒**：
 * ```
 * 跟你说多少遍了别用 IDM  → reason=question ⇒ 整场最强约束直接消失
 * ```
 * `question` 是不进 pending 的硬拒，所以这类漏点不可救。
 */
const REBUTTAL =
  /不是(?:已经)?(?:告诉|跟|给|对)(?:过)?你|我(?:已经|早就)?(?:跟你说过|告诉过你|讲过|强调过|说的是|要的是)|(?:跟|和|对)你说(?:过)?(?:多少|几)(?:遍|次)|说(?:过|了)(?:两|三|好几|\d+)(?:遍|次)|(?:强调|重申)(?:过|一?次)/;

/**
 * 用户**纠正 / 重申**句式：语义上等价于一条约束。
 *
 * ## 为什么单列一支
 *
 * 真实会话里最关键的约束常用反问表达：
 * ```
 * 不是告诉你音频在的位置了吗？你一点击下载，就会调起桌面的 IDM…
 * ```
 * 它没有 schema 谓词（「必须/不要」），却比任何命令式都强硬。
 * 判据是**封闭的词形集合**（说过 / 告诉过 / N 次），可枚举。
 */
export function deriveRebuttal(text: string): { subject: string; value: string } | null {
  const t = text.trim();
  if (!REBUTTAL.test(t)) return null;
  const body = t.replace(/[？?]+$/, '').trim();
  if (body.length < MIN_STATEMENT) return null;
  return { subject: '', value: body };
}

/**
 * 是否是一条记忆的完整判据链（拆三元组 + 语义闸门）。
 *
 * 单列成函数是为了让「拆不出」和「拆出来但不该收」走同一处，
 * 调用方不需要重复判。
 */
export function isPlannedNarration(text: string): boolean {
  return PLANNING_AFTER_DECLARATION.test(text.trim());
}

/** 是否是疑问句（提问不是断言）。 */
export function isQuestion(text: string): boolean {
  const t = text.trim();
  // ## 反问句不是提问
  //
  // 「不是告诉你音频在的位置了吗？」是在**强调已经说过**，语义上
  // 等价于一条禁令，是用户最强硬的纠正信号。把它当提问丢掉，
  // 等于丢掉整场会话里最该被记住的那句。
  if (REBUTTAL.test(t)) return false;
  if (QUESTION_TAIL.test(t)) return true;
  // ## 解释类动词豁免**必须先于**疑问判据（★2026-11-15 第二轮审查 P1-1）
  //
  // ```
  // 能否说明为什么必须用 pnpm   ← 「说明」在前 ⇒ 在解释原因，不是提问 ⇒ 收
  // 说明为什么必须用 pnpm       ← 同上
  // ```
  // 首版把 `A_NOT_A_QUESTION` 放在豁免之前，`能否说明…` 被硬拒。
  // 现在两条疑问判据（结构式 / 枚举式）统一走同一个豁免闸门。
  const m = QUESTION_WORD.exec(t);
  const anotA = A_NOT_A_QUESTION.exec(t) ?? A_NOT_A_HAS.exec(t);
  const hit = m !== null ? m : anotA;
  if (hit === null) return false;
  // 疑问词前是解释类动词 ⇒ 在解释原因，不是提问
  const before = t.slice(0, hit.index).trim().replace(/[，,：:\s]+$/, '');
  if (EXPLANATION_VERB.test(before)) return false;
  return true;
}

/**
 * 一条陈述是否在讲过程中的自己。
 *
 * 两类形态：
 * 1. **显式第一人称**（`我先看一下` / `让我确认`）—— 两个来源都适用
 * 2. **时间副词开头**（`接下来把 X 改成 Y`）—— 主语被省略成「我」
 *
 * ## 第 2 类只对**助手正文**生效（★2026-11-14）
 *
 * 同一个开头在两种来源里语义相反：
 * ```
 * 助手：接下来把遮罩颜色改成可继承的变量   ← 我在执行（过程）
 * 用户：接下来要保证用户能持续用下去       ← 我的要求（意图/约束）
 * ```
 * 用户在说「接下来要…」时是在**下达要求**，那正是该记的内容；
 * 助手说同样的开头是在**叙述自己的下一步动作**。
 *
 * 来源维度是唯一可靠的区分（与 `pathLocations` 只对用户生效同理）。
 *
 * @param text - 待判定的句子
 * @param origin - 来源；不传时按「助手」处理（最保守：多拒过程叙述）
 */
export function isProcessNarration(text: string, origin: 'user' | 'assistant' = 'assistant'): boolean {
  const t = text.trim();
  if (PROCESS_NARRATION.test(t)) return true;
  if (origin !== 'assistant') return false;
  if (AGENT_EXECUTION.test(t)) return true;
  // ## 分句内的执行叙述（★2026-11-15 真实残留）
  //
  // 上面两层只看**句首**，但实测助手常把完成态和执行意图连写：
  // ```
  // 读完了，接下来改              ← 第 2 分句才是执行意图
  // 看完了，然后改成变量          ← 同上
  // ```
  // 判断依据是分句标记（逗号/句号）**之后**紧跟时间副词 —— 那必然是
  // 时间线叙述，而可复用结论不会用「，接下来」这种衔接。
  //
  // 只对时间副词生效，不放大到「我」（`这个方案更好，我建议…` 是判断）。
  if (CLAUSE_TEMPORAL.test(t)) return true;
  // ## 分句首的执行动作（★2026-11-15 真实残留）
  //
  // `CLAUSE_TEMPORAL` 只认时间副词引出；实测残留里动作由「我 / 于是 / 开始」
  // 引出（见 `CLAUSE_ACTION` 注释）。这里补的是**位置**不是词表。
  if (CLAUSE_ACTION.test(t)) return true;
  return false;
}

/**
 * 剥掉指代后是**纯位置短语** —— 参照物不在句内（★2026-11-15 真实误收）。
 *
 * ## 为什么「长度够」不等于「自足」
 *
 * `isSelfContained` 原本只有一条长度判据：剥掉指代后剩余 ≥ 6 字即放行。
 * 实测漏掉了这一整类：
 * ```
 * 它的旁边是一个空洞的虚线框     ← 剥剩「的旁边是一个空洞的虚线框」
 * 它周围是朱砂边框              ← 剥剩「周围是朱砂边框」
 * ```
 * 两句都过了长度闸门并入库，但**「它」指什么无人知道**。
 *
 * ## 判据分两档（★2026-11-15 独立审查修正）
 *
 * 关键是**参照物是不是纯代词**：
 * ```
 * 它的旁边是…          ← 参照物「它」，句内无从得知 ⇒ 不自足
 * 这个按钮的右边是图标   ← 参照物「按钮」，就在句内   ⇒ 自足
 * 这个仓库的中间有 443 个项目 ← 参照物「仓库」在句内 ⇒ 自足
 * ```
 *
 * 而 `isSelfContained` 只在**剥掉指代后**调用本判据，所以：
 * - `rest` 以方位词开头（含前导「的」）⇒ 参照物是刚被剥掉的代词 ⇒ 拒
 * - `rest` 里有其他名词在方位词前   ⇒ 参照物在句内   ⇒ 收
 *
 * ## 为什么不能带任意前缀（独立审查推翻上一版）
 *
 * 上一版写成 `^(?:[^，。；：]{0,6})?(?:旁边|…)`，`{0,6}` 让方位词前可以
 * 有任意 6 个字符，实测误杀了一批主语在句内的句子：
 * ```
 * 这个仓库的中间有 443 个项目   ← 独立审查的实测反例
 * 这个文件的下方有一条注释
 * 这个面板的右侧是工具栏
 * ```
 * 所以必须**正向锚定在句首**，只容许前导「的」（`它的旁边` 剥掉「它」后剩「的旁边」）。
 */
const POSITIONAL_SUBJECT =
  /^的?(?:旁边|左侧|右侧|左边|右边|上方|下方|上面|下面|里面|内部|外面|周围|中间|后面|前面|身边|身上|底下|对面|两侧|两端|四周|附近|隔壁|顶部|底部)\s*(?:是|为|在|有|放|装|摆)/;

/**
 * 是否**自足**：脱离上下文能看懂。
 *
 * 判据：以指代词开头，且剥离指代后没有留下具体主体。
 * 不用长度、不用词表 —— 那两个维度已经被证明分不开这类残句。
 */
export function isSelfContained(text: string): boolean {
  const t = text.trim();
  const head = DEMONSTRATIVE_HEAD.exec(t);
  if (head === null) return true;
  const rest = t.slice(head[0].length).trim();
  // ## 剥掉指代后是**位置短语** ⇒ 主体仍未确定（★2026-11-15 真实误收）
  //
  // ```
  // 它的旁边是一个空洞的虚线框      ← 入库了，但「它」是什么？无人知道
  // 这个按钮的右边是图标            ← 同上
  // 它的左侧是工具栏                ← 同上
  // 这些项目的许可证各不相同         ← 这个是具体主体，必须收
  // 这个仓库的中间层有 443 个项目    ← 「中间层」是名词，不是方位短语
  // ```
  // 位置短语只描述**相对关系**，参照物（「它」）不在句内 —— 与承接代词
  // 是同一类缺陷：剥掉指代后长度够了，但长度不等于自足。
  //
  // 判据是「方位词 + 系词」两步：只认方位词**紧跟谓词**的形态。
  // 单纯的长度判据对这两类零区分力。
  if (POSITIONAL_SUBJECT.test(rest)) return false;
  // 剥掉指代后剩余过短 ⇒ 主体就是那个「这」，不自足
  if (rest.replace(/[\s，。；：、！？]/g, '').length < 6) return false;
  return true;
}

/** 路径类 token（与 `memory-filter.ts` 的 `maskPaths` 同源，此处局部实现避免循环依赖）。 */
const PATH_TOKEN =
  /\bhttps?:\/\/[^\s，。；：、！？"'`（）()【】\[\]{}<>《》「」]+|[A-Za-z]:[\\/][^\s，。；：、！？"'`（）()【】\[\]{}<>《》「」]*|\\\\[^\s，。；：、！？"'`（）()【】\[\]{}<>《》「」]*|(?:[A-Za-z0-9_.~-]+[\\/])+[A-Za-z0-9_.~-]*|[^\s，。；：、！？"'`（）()【】\[\]{}<>《》「」]+\.(?:md|txt|ts|tsx|js|jsx|mjs|cjs|json|ya?ml|toml|ini|png|jpe?g|gif|svg|webp|pdf|docx?|xlsx?|pptx?|csv|log|mp4|mp3|wav|sh|ps1|zip)\b/gi;

/** 把路径 token 挖成等长空格（保持下标对齐）。 */
function maskPathTokens(text: string): string {
  return text.replace(PATH_TOKEN, (token) => ' '.repeat(token.length));
}

/**
 * 成对引用片段（反引号 / 书名号 / 直角引号 / 弯引号 / 直引号）。
 *
 * ## 为什么谓词必须能落在引用内部时被排除（★2026-11-14 真实碎片）
 *
 * 实测 session-d08bcd4c 的 4 条「约束」**全部**是这种形态：
 * ```
 * TraeAgent 覆盖成"必须调用 `task_done` 工具"      ← 谓词「必须」在引号内
 * `server/` 只有一份 Readme 写着"不要用于生产"       ← 谓词「不要」在引号内
 * `project_path / must _patch / patch_path` 全是可变实例属性  ← must 来自字段名
 * ```
 * 引用内容是**被谈论的对象**，不是作者的主张。把引用里的词当谓词，
 * 切出的三元组主语必然带半截引号（`TraeAgent 覆盖成"`），是无意义碎片。
 *
 * 与 `maskPathTokens` 同一手法：挖成等长空格保持下标对齐，这样
 * `best.at` 仍可直接用于原文切片。未成对的引号不处理 ——
 * 那种情况由 `hasUnpairedQuote` 整句否决。
 */
const QUOTED_SEGMENT = /`[^`]*`|「[^」]*」|『[^』]*』|“[^”]*”|"[^"]*"/g;

function maskQuotedSegments(text: string): string {
  return text.replace(QUOTED_SEGMENT, (segment) => ' '.repeat(segment.length));
}

/**
 * 从一句自然语言里拆出 `(kind, subject, predicate, value)`。
 *
 * ## 为什么先按分句切
 *
 * 谓词可能出现在任意一个分句里：
 * ```
 * 以后都用 pnpm，别用 npm        ← 谓词在第二分句
 * 缓存必须放在工作区之外，否则…   ← 谓词在第一分句
 * ```
 * 整句直接找谓词会让「主语」带上半个句子（`…，别`），拆出的三元组是碎片。
 * 所以**逐分句**尝试，取第一个能拆出完整三元组的分句。
 *
 * @param statement - 陈述句（已去前缀）
 * @param hint - 调用方已知的类别（标签路径用）
 * @returns 拆不出三元组时返回 `null` —— 此时**它不是一条记忆**
 */
export function deriveClaim(
  statement: string,
  hint?: FactKind,
): { kind: FactKind; subject: string; predicate: string; value: string } | null {
  const text = statement.trim();
  if (text.length < MIN_STATEMENT) return null;
  // 机器输出不是句子：JSON / 键值片段里也能命中谓词裸词
  // （`{"结论是":"ok"}`、`err=定位到`），必须在拆三元组之前挡掉。
  if (/^[{\[]/.test(text) && text.includes('"')) return null;
  if (/"[^"]{1,40}"\s*:/.test(text)) return null;

  const clauses = text
    .split(/[，,；;]/)
    .map((c) => c.trim())
    .filter((c) => c.length > 0);
  const candidates = clauses.length > 1 ? clauses : [text];
  for (const clause of candidates) {
    const claim = deriveFromClause(clause, hint);
    if (claim !== null) return claim;
  }
  return null;
}

/**
 * 单个分句的三元组拆分（`deriveClaim` 的内部实现）。
 *
 * 分句内不再含逗号，因此「主语/取值里出现分句标点」只可能是冒号等残余。
 */
function deriveFromClause(
  clause: string,
  hint?: FactKind,
): { kind: FactKind; subject: string; predicate: string; value: string } | null {
  const text = clause.trim();
  if (text.length < MIN_STATEMENT) return null;
  // 路径必须先挖空：`帮我排版 docs/禁止事项.md` 里的「禁止」是文件名
  //
  // 引用片段同样挖空：`"不要用于生产"` 里的「不要」是被引用的告示，
  // 不是作者的主张。两类遮蔽合并成一次，避免谓词来自被谈论的内容。
  const masked = maskQuotedSegments(maskPathTokens(text));

  let best: { kind: Exclude<FactKind, 'location' | 'fact'>; word: string; at: number } | null = null;
  for (const { kind, word } of ALL_PREDICATES) {
    if (hint !== undefined && hint !== kind && !(hint === 'constraint' && kind === 'goal')) continue;
    const at = masked.indexOf(word);
    if (at < 0) continue;
    // ## 单字谓词只看**后边界**（★2026-11-14）
    //
    // 「选」是合法谓词（`数据库选 PostgreSQL`），但它也出现在「可筛**选**」
    // 「**选**项」「推**选**」里 —— 会把整句拆成
    // `(可以：把这 443 条整理成一张可筛, 选, 的 Excel)` 这种无意义碎片。
    //
    // ## 为什么不能检查前边界
    //
    // 中文里谓词前面**必然**是汉字：
    // ```
    // 数据库选 PostgreSQL     ← 「库」+「选」
    // 这个仓库是一个聚合库     ← 「库」+「是」
    // ```
    // 检查前边界等于把所有中文单字谓词整类拒掉（实测标签路径 0 条入库）。
    // 真正能区分的是**后边界**：`可筛**选**的` 后面跟「的」，是词内成分；
    // `数据库选 PostgreSQL` 后面跟空格 + ASCII 专名，是真谓语。
    if (word.length === 1 && !COPYULA_SINGLE.includes(word)) {
      const after = masked[at + 1] ?? '';
      if (/[\u4e00-\u9fa5]/.test(after)) continue;
    }
    // ## 取**最靠前**的谓词，而不是最长的（★2026-11-14）
    //
    // 一个分句只在**第一个**谓词处切分：它右边整段都是取值，因此后面
    // 出现的谓词是「取值内部」的词，不是本句的谓语。
    //
    // 反例（真实会话）：
    // ```
    // 后果是 `asyncio.gather` 的并行工具调用只能并行到第一个真 I/O 就串行化
    // ```
    // 按「最长词优先」会选中后面的「只能」，切出的主语变成
    // `后果是 …的并行工具调用` —— 主语里残留一个「是」，是错位的三元组。
    // 取最靠前的「是」后，取值过长自然被 `MAX_VALUE_CHARS` 拦掉。
    if (best === null || at < best.at || (at === best.at && word.length > best.word.length)) {
      best = { kind, word, at };
    }
  }
  if (best === null) return null;

  // 指向型 / 承接型分句：单独看不构成一条可复用信息
  if (LEADING_CONJUNCTION.test(text)) return null;
  // 「这/它」开头的**纯承接句**（`这样的话就…` / `这就是问题`）不是记忆；
  // 但「这个仓库收录了 443 个项目」是主语修饰语，必须收。
  if (startsWithBareDemonstrative(text)) return null;
  // 依赖上下文的从句（条件/处置/并列选项）：语义不闭合
  if (DEPENDENT_CLAUSE.test(text)) return null;
  // ## 无主语时的判据
  //
  // 中文可以省略主语的只有两类：
  // 1. **祈使句**（`必须用 pnpm`、`禁止连 3099`）—— 让人守规矩
  // 2. **自足的宣告句**（`改用 --stdin 传入`、`结论是旧进程未退出`）——
  //    省略的主语是「我们/本次工作」，语义完整
  //
  // 而 `不能直接提交`、`只能按分类查看` 既不祈使也不宣告，纯属从句碎片。
  //
  // 因果连词（所以/因此）不算主语，它们只是衔接推理：`因此改用 X` 里
  // 「因此」会被当作 subject，而真正的谓词是完整宣告 ⇒ 允许。
  const leadingPredicate = best.at === 0;
  if (leadingPredicate && !IMPERATIVE_PREDICATE.test(best.word)) {
    // 宣告类：谓词本身是**决策/结论/目标**的引导词，且取其比较完整
    const declarative =
      (best.kind === 'decision' || best.kind === 'conclusion' || best.kind === 'goal') && best.word.length >= 2;
    // 英文谓词：英语祈使句/陈述句省略主语是标准形态（`must use 3111`）
    const english = /^[A-Za-z ]+$/.test(best.word);
    if (!declarative && !english) return null;
  }
  // ## 因果连词必须**先于**结尾连词剥离（★2026-11-15 第二轮审查 P1-3）
  //
  // ```
  // 从而必须重启服务
  //   先剥结尾连词 → 「从」   ← 「而」被 `LEADING_CONJUNCTION` 的结尾规则吃掉
  //   先判因果连词 → 「从而」 ← 正确
  // ```
  // 顺序颠倒会产出**单字脏主语**，`factKey` 变成 `constraint|从|必须`。
  const rawSubject = text.slice(0, best.at).trim();
  const subjectIsCausalOnly = LEADING_CAUSAL.test(rawSubject) && rawSubject.length <= 4;
  // 结尾的连词（`…，并` / `…，且`）说明谓词是被并列到后半句的
  const subject = subjectIsCausalOnly
    ? rawSubject
    : rawSubject.replace(/[，,；;：:]?\s*(?:并|且|而|但|却|也|还|就|才|则)\s*$/, '').trim();
  // ## 纯因果连词作主语 ⇒ 等同于无主语
  //
  // `因此改用 compactRegion` 的 subject 是「因此」，它只是衔接词。
  // 若谓词是完整宣告（决策/结论/目标）就允许；否则仍按「缺主语」拒。
  if (subjectIsCausalOnly && !(best.kind === 'decision' || best.kind === 'conclusion' || best.kind === 'goal')) {
    return null;
  }
  // ## 主语是**纯时间词** ⇒ 等同于无主语（★2026-11-14 真实残留）
  //
  // ```
  // 现在换成真正的方印：石质方身、篆意的「志」字
  // → (现在, 换成, 真正的方印…)      ← 「现在」不是主语
  // ```
  // 时间词只是状语。「现在 / 接下来 / 之后」在主语位置，说明真正的
  // 主语被省略成了「我」。
  //
  // ## 但带**情态**的句子必须放行
  //
  // ```
  // 现在不再使用插件默认值      ← 用户拍板的约定（真记忆）
  // 目前只支持 Windows          ← 事实约束（真记忆）
  // 现在换成真正的方印：…        ← 执行动作（过程）
  // ```
  // 区别在谓词性质：`不再/只/必须` 是**状态断言**，`换成/改成` 是**动作**。
  // 因此只对「动作类谓词」生效 —— 情态谓词（IMPERATIVE_PREDICATE 里的
  // 必须/禁止/只能/不要…）豁免。
  if (TIME_ADVERB_ONLY.test(subject) && !IMPERATIVE_PREDICATE.test(best.word)) {
    // `不再` 这类否定副词不是词表里的谓词，单独豁免
    if (!/^(?:不再|无需|无需再|已经|仍然|仍)/.test(best.word)) return null;
  }
  // 取值：谓词之后的部分，跳过冒号与逗号，并去掉句尾残留标点
  const value = text
    .slice(best.at + best.word.length)
    .trim()
    .replace(/^[：:，,\s]+/, '')
    .replace(/[：:，,。；;！!？?\s]+$/, '')
    .trim();
  // ## 谓词是**名词短语的一部分** ⇒ 不是谓语（★2026-11-14 真实碎片）
  //
  // ```
  // 看过决定不收的，写进 excluded.json      ← 「决定不收的」是定语
  // 新手建议先用社区版」——新手真正该选的是…  ← 引号内被引用的短语
  // ```
  // 判据：
  // 1. 取值以「的 / 了 / 过」收尾 ⇒ 后面接的是修饰成分，不是完整取值
  // 2. 主语或取值含**不成对的引号 / 破折号** ⇒ 是从引用的短语里切出来的
  if (/(?:的|了|过|过的|了的)$/.test(value)) return null;
  if (hasUnpairedQuote(`${subject}${value}`)) return null;
  // 取值不存在或过短 ⇒ 是残句（`这必须用上` 的 value 是 `上`）
  if (value.replace(/[\s，。；：、！？"'`]/g, '').length < MIN_VALUE_CHARS) return null;
  // 空指针取值（`原因如下：`）不是信息
  if (EMPTY_POINTER.test(value)) return null;
  // 取值过长 ⇒ 谓词是定语/从句里的词，不是谓语
  if (value.length > MAX_VALUE_CHARS) return null;
  // ## 主语是纯人称代词 ⇒ 不自足
  //
  // ```
  // 我改成让底层动画真正淡出        ← 「我」是谁？脱离上下文不可用
  // 缓存必须放在工作区之外          ← 谁都懂
  // ```
  // 但**同时含第二人称与第一人称**的句子是「引用对方的话」，
  // 属于对话过程（`你想看到我主动提出一套设计，由我决定…`），直接拒。
  if (/你/.test(subject) && /我/.test(subject)) return null;
  const subjectNoPronoun = subject
    .replace(/^(?:那么|所以|但是|而且|另外|其实|然后)?\s*(?:我|我们|你|你们|他|她|它)\s*(?:们)?/g, '')
    .trim();
  if (subject.length > 0 && subjectNoPronoun.replace(/[\s，。；：、！？"'`]/g, '').length === 0) {
    // 纯代词主语：只有「必须/不要」这类**祈使**语义才算全局规则，
    // 「我改成…」是自述过程，不是给后人的规矩。
    if (!/^(?:必须|务必|一定要|禁止|严禁|切勿|不得|不允许|不准|不许|杜绝|只能|只允许|一律|不要)$/.test(best.word)) {
      return null;
    }
  }
  // 指代型主语且无其他内容 ⇒ 不自足
  if (subject.length > 0 && !isSelfContained(subject + best.word + value)) return null;
  // ## 主语必须是**完整的名词短语**（★2026-11-14 真实碎片）
  //
  // 谓词切分只保证「谓词左边是一段文字」，不保证那段文字是主语。
  // 两类残句都会漏过去：
  // ```
  // 它想干的是 Aider repo-map 那件事     ← 主语「它想干的」是「的」字结构，不是名词
  // 定位窄：这是 SWE-bench 修复 agent    ← 主语「定位窄：这」是两句被冒号粘连
  // ```
  // 判据一看结尾二看内部：
  // 1. 以「的」收尾 ⇒ 「的」字短语（定语结构），主语中心词缺失
  // 2. 含冒号 ⇒ 前一段是独立的判断句，本句只是它的补语
  // 3. 含句末语气词或第二个谓词 ⇒ 两句话被粘连
  //
  // ## 注释标记前缀剥掉（在主语形态判据之前）
  //
  // `TODO: 不要用 IDM 下载` 里的冒号是标记分隔符，不是两句粘连。
  // 剥完主语为空 ⇒ 走省略主语那条路（祈使句本来就允许无主语）。
  const subjectShape = stripCommentMarker(subject).trim();
  if (subjectShape.length > 0) {
    if (/的$/.test(subjectShape)) return null;
    if (/[：:]/.test(subjectShape)) return null;
    if (/[。！!？?]/.test(subjectShape)) return null;
    // ## 主语里含未闭合的括号 ⇒ 取值是从括号里切出来的（★2026-11-14）
    //
    // ```
    // 系统生成认罪帖文案（基于用户身份设定）   ← 主语＝`系统生成认罪帖文案（`
    // ```
    // 谓词「基于」在括号内部，主语带半截括号说明这句被从括注里剥出来了。
    if (hasUnpairedBracket(subjectShape)) return null;
    // ## 主语只有**量词 / 指示词**而没有中心名词 ⇒ 不是主语（★2026-11-14）
    //
    // ```
    // 一款基于"反向德西效应"心理学原理     ← 主语＝`一款`，中心名词缺失
    // 这个是一个聚合仓库                  ← 主语＝`这个`，纯指代
    // ```
    // 文档里这类抄自列表项的残句极多（`一款基于…的产品`被切掉了「的产品」）。
    if (/^(?:一款|一个|一种|一套|一份|一条|一项|这个|那个|这些|那些|其|该|此)$/.test(subjectShape)) {
      return null;
    }
  }

  // ## 纯因果连词主语在 statement 里必须剥掉
  //
  // `因此改用 compactRegion` 重组成 `因此改用 compactRegion` 仍是可读的，
  // 但查重与注入时「因此」是噪声。剥掉后语义不变。
  const finalSubject = subjectIsCausalOnly ? '' : subject;
  // ## 目标必须可验收
  //
  // 「目标是降低成本」不含任何数字或界限词，无法判断做到没有 ——
  // 它只是方向，不是验收条件。
  if (best.kind === 'goal' && !GOAL_QUANTITY.test(value)) return null;
  // ## 「降到」类动词必须是目标而不是读数
  //
  // `压到 / 控制到 / 限制到` 是主动施为；`降到 / 减到` 在真实日志里
  // 绝大多数是**观测数据**（`占比从 6% 降到 3%`），必须带界限词才收。
  if (OBSERVATIONAL_GOAL_VERB.test(best.word) && !GOAL_BOUND_SUFFIX.test(value)) return null;
  // ## 单字谓词要求取值是**专名**
  //
  // 「选」/「用」这类单字在中文里构词极多（选择、用户、用处…）。只收
  // 「取值里含 ASCII 专名」的形态（`数据库选 PostgreSQL`、`用 pnpm`），
  // 从而挡掉 `我选择看一下这个文件`。
  if (best.word.length === 1 && !/[A-Za-z0-9]/.test(value)) return null;
  // ## 单字/双字「只能」类的**能力陈述**不是约束
  //
  // ```
  // 只能按分类查看               ← 描述搜索能力的限制（状态）
  // 只能用 3111 跑测试           ← 规则
  // ```
  // 区别在取值：能力陈述的取值是一个**动作**（查看/用/走），规则的取值是
  // 一个**具体对象**（端口号/包名/路径）。判据用「取值里有没有具体名词」。
  //
  // 这里只拦最常见的两种弱情态谓词，其余祈使词（必须/禁止/不要）不在此列 ——
  // 它们本身就是规则，即使取值是动作。
  if ((best.word === '只能' || best.word === '只允许') && !hasConcreteValue(value)) return null;
  // ## 取值以裸量词收尾 ⇒ 缺宾语（★2026-11-14 真实碎片）
  //
  // ```
  // 未选择时：底部无"下一步"按钮，必须选择一个    ← 「一个」后面没有名词
  // 必须完整经历五屏引导                        ← 「五屏引导」是宾语
  // ```
  // 文档里的条件分支被切出来后，动词的宾语常留在上一句。判据只认这一
  // 形态（动词 + 裸量词），不引入新词表：`一个/一下/这个/那个/一次`
  // 后面必须还有名词，否则语义不闭合。
  if (/(?:一个|一下|这个|那个|一次|一项|一条|一种)$/.test(value)) return null;
  // ## 陈述性谓词的严格约束
  if (best.kind === 'statement' && !passesStatementGate(best.word, subject, value)) return null;
  return { kind: best.kind, subject: finalSubject, predicate: best.word, value };
}

/**
 * 陈述性谓词（是 / 属于 / 收录了…）是否通过严格约束。
 *
 * ## 为什么必须有这一组闸门
 *
 * 「是」是中文最高频的系词。裸用会把整类垃圾收进来，而 statement 类
 * 的**误收代价比漏收高**：它会被当成「用户问题的答案」注入快照。
 *
 * 四道闸门，全部来自真实会话的反例：
 *
 * | 反例 | 闸门 |
 * |---|---|
 * | `是的，我明白了` | ① 主语必须有具体名词 |
 * | `这个是刚才那个文件` | ② 排除指代型主语 |
 * | `问题是我还不知道能不能跑` | ③ 排除疑问 / 否定 / 推测 |
 * | `是这个意思吗` | ④ 取值必须 ≥4 字且非虚指 |
 */
function passesStatementGate(word: string, rawSubject: string, value: string): boolean {
  const subject = rawSubject.trim();
  // ① 主语必须有具体名词：至少 2 个中文字，且不是纯虚词
  const subjectBody = subject.replace(/[\s，。；：、！？"'`（）()]/g, '');
  if (subjectBody.length < 2) return false;
  // ## ② 指代型主语的判定必须看**整个主语**，不能只看是否恰好等于指代词
  //
  // ```
  // 这个是刚才那个文件        ← 主语「这个」纯指代 ⇒ 拒
  // 这个仓库收录了 443 个项目  ← 主语「这个仓库」指代 + 具体名词 ⇒ 收
  // ```
  // 首版写成 `/^(?:这|那|它|其|该|此)(?:个|些|样|种|里|儿)?$/`（整串匹配），
  // 于是「这个仓库」因为多了「仓库」两个字而被放行 —— 方向对；但真正的
  // 反例是相反的情况：剥掉指代词后**不剩具体名词**。
  const withoutDemonstrative = subjectBody.replace(/^(?:这|那|它|其|该|此)(?:个|些|样|种|位|款)?/, '');
  if (withoutDemonstrative.length === 0) return false;
  // 剥完只剩虚词（`样的` / `些的`）⇒ 仍是纯指代
  if (withoutDemonstrative.length < 2) return false;
  // ③ 排除应答（`是的`）、否定（`不是`）、推测（`可能是` / `似乎是` / `应该是`）
  if (/^(?:是的?|不是|并非|就是)$/.test(subjectBody)) return false;
  if (/^(?:可能|似乎|应该|大概|也许|或许|好像)/.test(subjectBody)) return false;
  // ④ 取值必须够实：≥4 个实字符，且不是纯虚指
  const valueBody = value.replace(/[\s，。；：、！？"'`（）()]/g, '');
  if (valueBody.length < 4) return false;
  if (/^(?:吗|呢|吧|了|的|啊|呀|嘛)$/.test(valueBody)) return false;
  // 疑问语气：取值里有疑问词或问号 ⇒ 是在提问不是在陈述
  if (/[？?]/.test(value)) return false;
  if (/(?:吗|呢)\s*$/.test(value)) return false;
  // ⑤ 单字「是」要求主语含 ASCII 专名或 ≥4 字具体名词，
  //    否则 `这是一个问题` / `他是好人` 这类泛泛句会全部通过。
  if (word === '是') {
    const hasProperNoun = /[A-Za-z0-9]/.test(subject);
    if (!hasProperNoun && subjectBody.length < 4) return false;
  }
  return true;
}

/**
 * 是否含**不成对的引用标记**：说明文本是从引号内被切出来的片段。
 *
 * ```
 * 新手建议先用社区版」——新手真正该选的是…   ← 只剩右引号
 * 「文档较少，新手建议先用社区版              ← 只剩左引号
 * ```
 * 这类碎片跨句拼接，语义完全错乱（实测真实会话抽出 1 条）。
 *
 * 同时检查 `——`（破折号）：出现则说明是「A——B」的并列/解释结构，
 * 拆出来的单侧往往不完整。
 */
function hasUnpairedQuote(text: string): boolean {
  const pairs: ReadonlyArray<readonly [string, string]> = [
    ['「', '」'],
    ['『', '』'],
    ['“', '”'],
    ['（', '）'],
    ['(', ')'],
    ['《', '》'],
  ];
  for (const [open, close] of pairs) {
    const opens = text.split(open).length - 1;
    const closes = text.split(close).length - 1;
    if (opens !== closes) return true;
  }
  // 破折号：`A——B` 的两侧单独拿出来都不完整
  if (text.includes('——')) return true;
  return false;
}

/**
 * 是否含**未闭合的括号**（只查圆括号与方括号，不管引号）。
 *
 * ## 为什么与 `hasUnpairedQuote` 分开（★2026-11-14）
 *
 * `hasUnpairedQuote` 会顺带检查破折号，而主语里出现破折号
 * （`主线——主体循环`）未必说明主语不完整。这里只关心「括注被切了一半」：
 * ```
 * 系统生成认罪帖文案（基于用户身份设定）   ← 主语带半截 `（`
 * ```
 */
function hasUnpairedBracket(text: string): boolean {
  const pairs: ReadonlyArray<readonly [string, string]> = [
    ['（', '）'],
    ['(', ')'],
    ['【', '】'],
    ['[', ']'],
  ];
  for (const [open, close] of pairs) {
    const opens = text.split(open).length - 1;
    const closes = text.split(close).length - 1;
    if (opens !== closes) return true;
  }
  return false;
}

/**
 * 取值里是否含**具体对象**（而不是泛泛的动作）。
 *
 * `3111` / `pnpm` / `D:\Desktop` / `工作区之外` 算具体；
 * `按分类查看` / `这样处理` 只是动作描述。
 */
function hasConcreteValue(value: string): boolean {
  // ASCII 专名（端口、包名、路径、参数）
  if (/[A-Za-z0-9]/.test(value)) return true;
  // 中文里的具体对象名词（位置、产物、部件）
  return /(?:端口|目录|文件夹|路径|工作区|缓存|配置|文件|音频|视频|图片|脚本|密钥|参数|环境|分支|提交|首页|封面|字体|配色|版式|动效)/.test(
    value,
  );
}

/**
 * 资源位置的三元组：`音频在桌面` → `(音频, 位于, 桌面)`。
 *
 * 单列一支是因为位置句**没有谓词词表**可依 —— `在 / 放在 / 位于`
 * 是中文最高频虚词，靠它做二分类四轮全失败。但作为**三元组拆分**它
 * 可靠的前提是：`在` 后面必须是**真正的位置**。
 *
 * ## 为什么「在」的宾语必须过白名单
 *
 * 「在」在中文里既表处所也表时间/状态：
 * ```
 * 音频在桌面                        ← 位置
 * 把这个包嵌到 DSH 的架构里面        ← 处所但不是「资源在哪」
 * 现在我们是在进行 DSH 的配置        ← 进行态（在 + 动词）
 * 我在任何一个对话里面都能用         ← 范围，不是位置
 * ```
 * 白名单是**收敛的**（位置词是有限集合），黑名单是发散的。
 */
const PLACE_NOUN =
  /(?:桌面|下载目录|文档目录|视频目录|目录|文件夹|盘|硬盘|网盘|云盘|U\s*盘|移动硬盘|本地|本机|电脑|服务器|共享|onedrive|素材库|assets|build|dist|public|temp|tmp|工作区|项目|工程|当前目录|根目录|子目录|同目录|上级目录|这里|这儿|那儿|路径)/;

const LOCATION_VERB = /(?:位于|放在|放到|存在|来自|存到|拷到|复制到|在)/;

export function deriveLocation(
  text: string,
): { subject: string; predicate: string; value: string } | null {
  const t = text.trim();
  const m = LOCATION_VERB.exec(t);
  if (m === null) return null;
  const verb = m[0];
  const at = m.index;
  const subject = t.slice(0, at).trim();
  const value = t.slice(at + verb.length).trim().replace(/^[：:，,\s]+/, '');
  if (subject.replace(/[\s，。；：、！？]/g, '').length < 2) return null;
  if (value.replace(/[\s，。；：、！？"'`]/g, '').length < 2) return null;
  // ## 主语含冒号 ⇒ 两句粘连（★2026-11-14 真实缺陷）
  //
  // ```
  // 用户点击后立即退出：数据已位于点击时写入本地
  // ```
  // 冒号前面是独立的断言句，后面才是被切的部分 —— 与谓词拆分的
  // 「主语形态」判据同理，冒号说明这里不是主语。
  if (/[：:]/.test(subject)) return null;
  // ## 取值在第一个逗号处截断（★2026-11-14 真实缺陷）
  //
  // ```
  // 数据已位于 点击时写入本地，下次启动时同步    ← 逗号后是并列动作
  // 音频在桌面，文案在下载目录                  ← 逗号后是**另一条**位置
  // ```
  // 前者应整句拒（截断后不含地点成分）；后者应保留前一条（截断后是
  // `桌面`，含地点成分）。直接「含逗号就拒」会把后者也丢掉 ——
  // 那是用户明确交代的两个目录之一。
  const valueAtFirstComma = value.split(/[，,；;]/)[0].trim();
  if (valueAtFirstComma.length === 0) return null;
  // ## 位置句的取值必须是**地点**，不能是一段动作（★2026-11-14 真实缺陷）
  //
  // 实测 session-95eaf7e3（用户贴产品文档）抽出：
  // ```
  // (用户点击后立即退出：数据已, 位于, 点击时写入本地，下次启动时同步)
  // ```
  // `位于` 在这里是「值等于/处于某状态」的书面说法，不是地点。
  // 「在」已经有 PLACE_NOUN 闸门，`位于 / 放在 / 存在` 等却完全没有 ——
  // 它们是书面语，恰好在正式文档里高频出现。
  //
  // 判据：取值里必须含**地点性成分**（位置名词 / 盘符 / 路径 / 媒体文件）。
  // 这与「在」的闸门同理：位置词是有限集合，动作描述是开放集合。
  const hasPlace =
    PLACE_NOUN.test(valueAtFirstComma) ||
    /^[A-Za-z]:[\\/]/.test(valueAtFirstComma) ||
    /\.(?:wav|mp3|mp4|mov|png|jpe?g|gif|webp|md|txt|json|ts|js)\b/i.test(valueAtFirstComma) ||
    /[\\/]/.test(valueAtFirstComma);
  if (!hasPlace) return null;
  return { subject, predicate: '位于', value: valueAtFirstComma };
}

/** 校验结果。`ok: false` 必须带原因，供审计日志统计。 */
export type ValidateResult = { ok: true } | { ok: false; reason: string };

/**
 * **单一校验闸门**：任何路径产出的记忆都必须过这里，没有例外。
 *
 * 这是「全局性」唯一可验证的硬证据 —— 只要所有写入都经过本函数，
 * 补丁就不可能落在闸门之外。
 */
export function validateFact(fact: MemoryFact): ValidateResult {
  const statement = fact.statement.trim();
  // ## 指针 Fact 只校验结构完整性
  //
  // 它的 statement 是代码生成的（`文档已存入工件库（12345 字符，hash=…）：首行预览`），
  // 主语固定、无过程叙述、无指代 —— 自足性与「像不像句子」这类**语义**判据
  // 对它没有意义。只保留「三元组齐全 + hash 合法」这一条硬约束。
  if (fact.kind === 'artifact') {
    if (fact.value.trim().length === 0) return { ok: false, reason: 'no_value' };
    if (!/^[0-9a-f]{8,64}$/i.test(fact.value.trim())) return { ok: false, reason: 'bad_artifact_hash' };
    if (fact.predicate.trim().length === 0) return { ok: false, reason: 'no_predicate' };
    if (statement.length < MIN_STATEMENT) return { ok: false, reason: 'statement_too_short' };
    return { ok: true };
  }
  if (statement.length < MIN_STATEMENT) return { ok: false, reason: 'statement_too_short' };
  if (statement.length > MAX_STATEMENT) return { ok: false, reason: 'statement_too_long' };
  // ## 残留的 markdown 标记 ⇒ 是片段不是句子
  //
  // `什么时候提交**：完成小改动就提交` 这类破了标记的片段说明原文是从
  // 列表/加粗里切出来的，语义边界已被破坏。
  if (/\*\*|__|`{2,}|^\s*[-*+]\s/.test(statement)) return { ok: false, reason: 'markup_fragment' };
  // ## 规则路径仍要求三元组（★2026-11-14 修订）
  //
  // 上一版曾把这两条删掉，结果实测「是的，我明白了」「这个是刚才那个文件」
  // 「代码已全部读完，结论如下」全部涌进来 —— **结构判据对垃圾与真判断句
  // 零区分力**（82/82 全通过，5/5 全通过）。
  //
  // 所以正确的分工是：
  // - **规则路径**（本函数）：只有拆出三元组才算自证成立，零成本直接入库
  // - **LLM 路径**（`validateJudgedFact`）：语义已由模型裁决，不再要求三元组
  //
  // 拆不出三元组的句子不是「拒绝」，而是「待裁决」，进入 `pending` 队列。
  if (fact.predicate.trim().length === 0) return { ok: false, reason: 'no_predicate' };
  if (fact.value.trim().length === 0) return { ok: false, reason: 'no_value' };
  if (!isSelfContained(statement)) return { ok: false, reason: 'not_self_contained' };
  // 过程叙述按来源判：用户说「接下来要…」是要求，助手说才是过程
  if (isProcessNarration(statement, fact.origin)) return { ok: false, reason: 'process_narration' };
  if (fact.confidence < MIN_CONFIDENCE) return { ok: false, reason: 'low_confidence' };
  // 计划句式（`下一步目标是先把依赖装好`）不是可验收的目标
  if (isPlannedNarration(statement)) return { ok: false, reason: 'planned_narration' };
  // 提问不是断言
  if (isQuestion(statement)) return { ok: false, reason: 'question' };
  // 机器输出（JSON / 键值行）不是句子
  if (/^[{\[]/.test(statement) && statement.includes('"')) return { ok: false, reason: 'machine_output' };
  if (/"[^"]{1,40}"\s*:/.test(statement)) return { ok: false, reason: 'machine_output' };
  return { ok: true };
}

/**
 * 校验 **LLM 已裁决**的候选：不要求三元组（★2026-11-14）。
 *
 * ## 为什么需要第二道闸门
 *
 * 实测结论（7258 字符真实报告）：
 * ```
 * 候选句 82 条 → 结构判据全部通过（零区分力）
 *              → 95 词谓词白名单只剩 3 条（96% 误杀）
 * ```
 *
 * 结构判据对「是垃圾」与「是真判断句」**无区分能力**，能区分的是语义。
 * 因此：
 * - `validateFact`：规则路径用，**必须**有三元组（自证成立，零成本）
 * - `validateJudgedFact`：LLM 路径用，语义已由模型裁决，只保留
 *   **可计算的结构性底线**（长度 / markdown 碎片 / 机器输出 / 提问）
 *
 * 区别只有一点：不检查 `predicate` / `value` 是否为空。
 *
 * ## 为什么仍要保留结构底线
 *
 * 模型偶尔会把表格行、JSON 片段、半句话当成「结论」返回。这些不是语义
 * 判断，是**形态**问题，代码判得比模型准，且零成本。
 */
export function validateJudgedFact(fact: MemoryFact): ValidateResult {
  const statement = fact.statement.trim();
  if (fact.kind === 'artifact') return validateFact(fact);
  if (statement.length < MIN_STATEMENT) return { ok: false, reason: 'statement_too_short' };
  // LLM 候选允许更长：总结句天然比三元组重构句长
  if (statement.length > MAX_JUDGED_STATEMENT) return { ok: false, reason: 'statement_too_long' };
  if (/\*\*|__|`{2,}|^\s*[-*+]\s/.test(statement)) return { ok: false, reason: 'markup_fragment' };
  // 表格行：`| 优点 | 缺点 |`。模型常把表格当「结构化结论」返回，
  // 但它是被切掉表头的碎片，脱离上下文读不懂。
  if (/^\s*\|.*\|\s*$/.test(statement)) return { ok: false, reason: 'markup_fragment' };
  if (/^[{\[]/.test(statement) && statement.includes('"')) return { ok: false, reason: 'machine_output' };
  if (/"[^"]{1,40}"\s*:/.test(statement)) return { ok: false, reason: 'machine_output' };
  if (isQuestion(statement)) return { ok: false, reason: 'question' };
  if (isPlannedNarration(statement)) return { ok: false, reason: 'planned_narration' };
  return { ok: true };
}

/**
 * 构造**工件指针** Fact：一条指向工件库的引用，不带正文。
 *
 * ## 为什么它不需要三元组
 *
 * 其余类别的判据是「拆不出 (subject, predicate, value) 就不是记忆」，
 * 但指针 Fact 的语义由**结构**保证：
 * ```
 * subject   = 工件类型（文档 / 代码 / 日志）
 * predicate = 位于工件库
 * value     = <hash>（可被 lrc_fetch_artifact 直接取回）
 * ```
 * 三元组齐全，只是由代码而不是从自然语言拆出来 —— 因此不经过 `deriveClaim`。
 *
 * ## 为什么 statement 里要带预览
 *
 * 只写 hash 的话，模型在注入内容里看到 `[工件] abc123` 无法判断
 * 「这值不值得取回」。预览句（首行前 80 字）让它在不取回的情况下也能决策。
 *
 * @param input.hash - 工件 hash（`ArtifactStore.store()` 返回）
 * @param input.preview - 首行预览
 * @param input.chars - 原文字符数
 */
export function makeArtifactFact(input: {
  hash: string;
  preview: string;
  chars: number;
  kindLabel: string;
  origin: 'user' | 'assistant';
  sessionId: string;
  turn?: number;
}): MemoryFact {
  const preview = input.preview.trim();
  return {
    kind: 'artifact',
    subject: input.kindLabel,
    predicate: '位于工件库',
    value: input.hash,
    statement: `${input.kindLabel}已存入工件库（${input.chars} 字符，hash=${input.hash}）${
      preview.length > 0 ? `：${preview}` : ''
    }`,
    scope: 'session',
    origin: input.origin,
    confidence: 0.95,
    source: { sessionId: input.sessionId, turn: input.turn },
    status: 'active',
  };
}

/**
 * 从一段消息正文里提取**主题**（供 Fact 的上下文附加用）。
 *
 * ## 为什么用「首句」而不是段落/标题（实测决定）
 *
 * 实测 session-95eaf7e3 的 1578 条助手正文：
 * ```
 * 含 ≥2 段落:   88 条（ 5.6%）   ← 段落几乎不存在
 * 含 markdown 标题: 11 条（ 0.7%）   ← 标题几乎不存在
 * 有可用首句:     1566 条（99.2%）   ← 首句几乎总在
 * ```
 * DSH 的助手正文是「长段落 + 列表」的形态，没有稳定的结构锚点。
 * 首句是唯一覆盖率足够（99.2%）的锚点。
 *
 * ## 首句不是主题怎么办
 *
 * 实测首句质量尚可（`像素感这次是真的出来了`、`现状已经查清`、
 * `剩下还有一件事需要你来决定`）。它们确实是**这一段在讲什么**。
 * 少数以寒暄或标签开头的（`做完了`）会被裁短后仍可用 ——
 * 它至少限定「这是关于『做完了』那一轮」。
 *
 * ## 边界
 *
 * - 剥离 markdown 标记（`#`、`>`、`-`、`*`、行内 code 反引号）
 * - 去掉代码围栏块（``` 内的行不是主题）
 * - 长度上限 [`TOPIC_MAX_CHARS`]，超出截断
 * - 空/纯符号返回 `undefined`（调用方据此不附加 topic）
 */
export const TOPIC_MAX_CHARS = 40;

export function extractTopic(text: string): string | undefined {
  // 跳过代码围栏：围栏里的首行往往是 `const x = ...`，不是主题
  const lines: string[] = [];
  let inFence = false;
  for (const raw of text.split('\n')) {
    if (raw.trim().startsWith('```')) {
      inFence = !inFence;
      continue;
    }
    if (!inFence) lines.push(raw);
  }
  const body = lines.join('\n');

  // 优先取 markdown 标题（罕见但质量最高）
  const heading = /^#{1,6}\s+(.+)$/m.exec(body);
  const candidate =
    heading?.[1] ??
    // 否则取第一句：截到第一个句末标点或换行
    /^[^。！？\n]+/.exec(body.replace(/^[#>\-*+\s]+/gm, '').trim())?.[0];

  if (candidate === undefined) return undefined;
  const flat = candidate
    .replace(/`([^`]*)`/g, '$1') // 行内 code 去反引号
    .replace(/\*\*/g, '')
    .replace(/\s+/g, ' ')
    .trim();
  if (flat.length < 4) return undefined;
  const chars = Array.from(flat);
  return chars.length > TOPIC_MAX_CHARS
    ? `${chars.slice(0, TOPIC_MAX_CHARS).join('')}…`
    : flat;
}

/**
 * 由一句陈述构造 MemoryFact（**不做校验**，校验交给 `validateFact`）。
 *
 * 拆不出三元组时返回 `null` —— 调用方据此丢弃，不需要额外的长度门槛。
 */
export function makeFact(input: {
  statement: string;
  origin: 'user' | 'assistant';
  sessionId: string;
  turn?: number;
  hint?: FactKind;
  confidence?: number;
  /** 强制指定为资源位置（用户消息里由上游判定） */
  asLocation?: boolean;
}): MemoryFact | null {
  const raw = input.statement.trim().replace(/^[-*+\d.)\s]+/, '');
  if (raw.length === 0) return null;

  const loc = input.asLocation === true ? deriveLocation(raw) : null;
  const claim = loc !== null ? { kind: 'location' as FactKind, ...loc } : deriveClaim(raw, input.hint);

  // ## 拆不出三元组 ⇒ **未富集**，不是拒绝（★2026-11-14）
  //
  // 旧实现 `if (claim === null) return null` 把白名单当成了否决权。
  // 实测 82 条结构完全合格的陈述里只有 3 条能命中 95 词谓词表 ——
  // 「分层极其干净，改造成本低」这种真判断句全部被丢。
  //
  // 现在退化为「只带 statement 的记忆」：仍入库、仍注入、仍召回，
  // 只是不参与冲突判定（冲突判定需要 subject+predicate）。
  // 是否值得记由 `validateFact` 的结构判据 + LLM 兜底裁决，不由词表裁决。
  if (claim === null) {
    const scope: FactScope = TEMPORARY_MARKER.test(raw) ? 'session' : 'project';
    return {
      kind: input.hint ?? 'statement',
      subject: '',
      predicate: '',
      value: '',
      statement: raw,
      scope,
      origin: input.origin,
      confidence: input.confidence ?? 0.8,
      source: { sessionId: input.sessionId, turn: input.turn },
      status: 'active',
      enriched: false,
    };
  }

  // ## statement 用**三元组重组的句子**，不用原始长句
  //
  // `deriveClaim` 会拆到能成三元组的那一分句，若 statement 仍保留整句，
  // 校验（自足性 / 过程叙述 / 疑问句）就作用在半句子之外的内容上 ——
  // 实测「以后都用 pnpm，别用 npm」的三元组来自第二分句，但校验却在看
  // 第一分句，两边语义不一致。
  //
  // 重组规则：有主语就是 `主语 + 谓词 + 取值`，无主语就是 `谓词 + 取值`。
  // 中英交界处补空格，否则 `别用` + `npm` 会粘成 `别用npm`，
  // 既不便于阅读，也会让查重的 ASCII 取值 token 边界失准。
  const join = (left: string, right: string): string => {
    if (left.length === 0) return right;
    const needSpace = /[A-Za-z0-9]$/.test(left) || /^[A-Za-z0-9]/.test(right);
    return needSpace ? `${left} ${right}` : `${left}${right}`;
  };
  const head = join(claim.subject, claim.predicate === '位于' ? '位于' : claim.predicate);
  const statement = join(head, claim.value);
  const scope: FactScope = TEMPORARY_MARKER.test(raw) ? 'session' : 'project';
  return {
    kind: claim.kind,
    subject: claim.subject,
    predicate: claim.predicate,
    value: claim.value,
    statement: statement.trim(),
    scope,
    origin: input.origin,
    confidence: input.confidence ?? 0.8,
    source: { sessionId: input.sessionId, turn: input.turn },
    status: 'active',
    enriched: true,
  };
}

/** 渲染成注入文本：`[约束] 必须用 pnpm 替代 npm`。 */
export function renderFact(fact: MemoryFact): string {
  return `[${KIND_LABEL[fact.kind]}] ${fact.statement}`;
}

/**
 * 冲突键：同 subject + predicate 视为同一件事的不同取值。
 *
 * ## 未富集的 Fact 必须退化到 statement（★2026-11-14）
 *
 * 三元组为空时 `norm('')` 全是空串，所有未富集 Fact 会撞成同一个 key
 * `statement|||` —— 冲突检测会把它们当成「同一件事的不同取值」互相覆盖。
 * 因此退回 statement 的归一化形态：它们只与**自己重复**才算冲突。
 */
export function factKey(
  fact: Pick<MemoryFact, 'kind' | 'subject' | 'predicate'> & { statement?: string },
): string {
  const norm = (s: string): string => s.replace(/[\s，。；：、！？"'`（）()]/g, '').toLowerCase();
  // goal 与 constraint 归同一维度：`压到 200ms` 与 `不超过 200ms` 是同一件事
  const kind = fact.kind === 'goal' ? 'constraint' : fact.kind;
  if (fact.predicate.length === 0) {
    return `${kind}|statement|${norm(fact.statement ?? '')}`;
  }
  return `${kind}|${norm(fact.subject)}|${norm(fact.predicate)}`;
}

